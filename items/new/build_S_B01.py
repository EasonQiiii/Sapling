KP_INDEX = {}
for kp, *_ in DRAFTS:
    KP_INDEX.setdefault(kp, len(KP_INDEX))


def thinking_for(kp, slot):
    even = KP_INDEX[kp] % 2 == 0
    if slot == 0:   # a: basic
        return "按步骤做" if even else "先选方法或先把情境翻译成数学关系"
    if slot == 1:   # b: explain
        return "还要说明理由"
    return "还要说明理由" if even else "自己把几个关系串起来"   # c: synth


def build():
    items = []
    slot_count = {}
    for n, (kp, task, answer, note) in enumerate(DRAFTS, start=1):
        slot = slot_count.get(kp, 0)
        slot_count[kp] = slot + 1
        item = {
            "id": f"G5V1-S{n:03d}",
            "source": {"origin": "self", "note": f"自编测试题，依据 {kp}（覆盖补齐，第一批 S-B01）"},
            "task": task,
            "kp_main": kp,
            "kp_other": [],
            "thinking": thinking_for(kp, slot),
            "figure": None,
            "answer": answer,
        }
        if note:
            item["answer_note"] = note
        items.append(item)
    return items


