THINKING_OVERRIDE = {
    ("B2-04", 0): "认出来就做",
    ("B2-05", 0): "认出来就做",
    ("B3-01", 0): "认出来就做",
    ("B3-02", 0): "认出来就做",
    ("B3-04", 0): "认出来就做",
}


def thinking_for(kp, slot):
    if (kp, slot) in THINKING_OVERRIDE:
        return THINKING_OVERRIDE[(kp, slot)]
    even = KP_INDEX[kp] % 2 == 0
    if slot == 0:   # a: basic
        return "按步骤做" if even else "先选方法或先把情境翻译成数学关系"
    if slot == 1:   # b: explain
        return "还要说明理由"
    return "还要说明理由" if even else "自己把几个关系串起来"   # c: synth


def build(start_num=73, batch="S-B02"):
    items = []
    slot_count = {}
    for n, (kp, task, answer, thinking, note) in enumerate(DRAFTS, start=start_num):
        slot = slot_count.get(kp, 0)
        slot_count[kp] = slot + 1
        item = {
            "id": f"G5V1-S{n:03d}",
            "source": {"origin": "self", "note": f"自编测试题，依据 {kp}（覆盖补齐，第二批 S-B02）"},
            "task": task,
            "kp_main": kp,
            "kp_other": [],
            "thinking": thinking,
            "figure": None,
            "answer": answer,
        }
        if note:
            item["answer_note"] = note
        items.append(item)
    return items


if __name__ == "__main__":
    out = Path(__file__).with_name("S-B02.yaml")
    items = build()
    out.write_text(yaml.safe_dump(items, allow_unicode=True, sort_keys=False, width=10**6), encoding="utf-8")
    print(f"wrote {len(items)} drafts -> {out}")
